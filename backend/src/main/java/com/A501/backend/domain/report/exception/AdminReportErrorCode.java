package com.A501.backend.domain.report.exception;

import org.springframework.http.HttpStatus;

import com.A501.backend.common.exception.ErrorCode;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

@Getter
@RequiredArgsConstructor
public enum AdminReportErrorCode implements ErrorCode {

    CHILD_NOT_FOUND(
            HttpStatus.NOT_FOUND,
            "ADMIN_REPORT_CHILD_NOT_FOUND",
            "Child profile not found."),
    REPORT_DATE_NOT_PAST(
            HttpStatus.BAD_REQUEST,
            "ADMIN_REPORT_DATE_NOT_PAST",
            "Only a past report date can be generated by this endpoint."),
    SOURCE_NOT_FOUND(
            HttpStatus.NOT_FOUND,
            "ADMIN_REPORT_SOURCE_NOT_FOUND",
            "No reportable activity exists for the requested period."),
    REPORT_ALREADY_EXISTS(
            HttpStatus.CONFLICT,
            "ADMIN_REPORT_ALREADY_EXISTS",
            "A daily report already exists for this child and date.");

    private final HttpStatus status;
    private final String code;
    private final String message;
}
